"""Render the Gargoyl icons from gargoyle.svg using librsvg."""

import json
import shutil
import struct
import subprocess
import tempfile
from base64 import b64encode
from pathlib import Path
from xml.etree import ElementTree as ET

HERE = Path(__file__).resolve().parent
MARK = HERE / "gargoyle.svg"
OUT = HERE / "icon"
FAVICON_MODULE = HERE.parent / "gargoyl" / "dashboard" / "favicon.py"

SVG_NS = "http://www.w3.org/2000/svg"
PLATE = "#101312"
LINE = "#d9ded9"
EYES = "#3ee67f"
PNG_ICONS = (
    ("apple-touch-icon.png", 180, None),
    ("icon-192.png", 192, "any"),
    ("icon-512.png", 512, "any"),
    ("icon-maskable-512.png", 512, "maskable"),
)


def icon_svg(mark: ET.Element, maskable: bool) -> bytes:
    svg = ET.Element("svg", xmlns=SVG_NS, viewBox="0 0 512 512" if maskable else mark.attrib["viewBox"])
    plate = ET.SubElement(svg, "rect", width="100%", height="100%", fill=PLATE)
    group = ET.SubElement(svg, "g", color=LINE, fill=EYES)
    if maskable:
        group.set("transform", "translate(80 80) scale(5.5)")
    else:
        plate.set("rx", "12")
    for path in mark.findall(f"{{{SVG_NS}}}path"):
        ET.SubElement(group, "path", path.attrib)
    ET.indent(svg)
    return ET.tostring(svg, encoding="utf-8") + b"\n"


def render_png(rasterizer: str, svg: bytes, size: int) -> bytes:
    return subprocess.run(
        [rasterizer, "--width", str(size), "--height", str(size)],
        input=svg, stdout=subprocess.PIPE, check=True,
    ).stdout


def main() -> int:
    mark = ET.parse(MARK).getroot()
    rasterizer = shutil.which("rsvg-convert")
    if rasterizer is None:
        raise SystemExit("install librsvg (rsvg-convert) before regenerating the icons")

    favicon = icon_svg(mark, maskable=False)
    maskable = icon_svg(mark, maskable=True)
    files = {"favicon.svg": favicon, "icon-maskable-512.svg": maskable}
    icons = []
    for name, size, purpose in PNG_ICONS:
        files[name] = render_png(rasterizer, maskable if purpose == "maskable" else favicon, size)
        if purpose is not None:
            icons.append(dict(src=name, sizes=f"{size}x{size}", type="image/png", purpose=purpose))

    png = files["icon-512.png"]
    chunk = struct.pack(">4sI", b"ic09", 8 + len(png)) + png
    files["gargoyl.icns"] = struct.pack(">4sI", b"icns", 8 + len(chunk)) + chunk
    manifest = {
        "name": "Gargoyl",
        "short_name": "Gargoyl",
        "description": "Evidence you can inspect for inference-provider fleets.",
        "start_url": "../",
        "display": "standalone",
        "background_color": PLATE,
        "theme_color": "#0c0e0d",
        "icons": icons,
    }
    files["manifest.webmanifest"] = (json.dumps(manifest, indent=2) + "\n").encode()

    favicon_module = (
        '"""Generated by assets/render_icons.py."""\n\n'
        f'FAVICON_DATA_URL = "data:image/svg+xml;base64,{b64encode(favicon).decode("ascii")}"\n'
    ).encode()
    OUT.mkdir(parents=True, exist_ok=True)
    outputs = {OUT / name: data for name, data in files.items()}
    outputs[FAVICON_MODULE] = favicon_module
    with tempfile.TemporaryDirectory(dir=HERE) as temp:
        staging = Path(temp)
        for target, data in outputs.items():
            (staging / target.name).write_bytes(data)
        for target in outputs:
            (staging / target.name).replace(target)
            print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
